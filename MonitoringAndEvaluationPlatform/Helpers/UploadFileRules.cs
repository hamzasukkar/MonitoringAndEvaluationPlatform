namespace MonitoringAndEvaluationPlatform.Helpers
{
    /// <summary>
    /// Rules for user-uploaded attachments (projects, measures, requests, comments, framework goals).
    /// Uploads are saved under wwwroot/uploads and served as static files, so only document and image
    /// types are accepted, and the name the browser sends is never used in a path as-is.
    /// </summary>
    public static class UploadFileRules
    {
        public static readonly IReadOnlySet<string> AllowedExtensions = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx", ".csv", ".txt",
            ".jpg", ".jpeg", ".png", ".gif", ".webp"
        };

        /// <summary>Value for an &lt;input type="file" accept="..."&gt; attribute.</summary>
        public static string AcceptAttribute => string.Join(",", AllowedExtensions);

        /// <summary>
        /// The uploaded file's name with any directory part and any character Windows does not allow
        /// in a file name removed. IFormFile.FileName comes from the client and may contain a path.
        /// </summary>
        public static string SafeName(IFormFile file)
        {
            var name = Path.GetFileName((file.FileName ?? string.Empty).Replace('\\', '/'));
            var invalid = Path.GetInvalidFileNameChars();
            name = new string(name.Select(c => invalid.Contains(c) || c == ':' ? '_' : c).ToArray()).Trim(' ', '.');
            return name.Length == 0 ? "file" : name;
        }

        public static bool IsAllowed(IFormFile file) => AllowedExtensions.Contains(Path.GetExtension(SafeName(file)));

        /// <summary>Names of the non-empty files in the list whose type is not allowed.</summary>
        public static List<string> Rejected(IEnumerable<IFormFile>? files) =>
            files?.Where(f => f.Length > 0 && !IsAllowed(f)).Select(SafeName).ToList() ?? new List<string>();

        /// <summary>
        /// Disk path for a stored "/uploads/..." FilePath, or null when it would resolve outside
        /// wwwroot/uploads. Stored paths are generated by the server, but a database restored from
        /// another server cannot be assumed clean, so never read or delete by them unchecked.
        /// </summary>
        public static string? ResolveStoredPath(string webRootPath, string? storedPath)
        {
            if (string.IsNullOrWhiteSpace(storedPath)) return null;

            var uploadsRoot = Path.GetFullPath(Path.Combine(webRootPath, "uploads")) + Path.DirectorySeparatorChar;
            var relative = storedPath.TrimStart('/', '\\').Replace('/', Path.DirectorySeparatorChar);
            var fullPath = Path.GetFullPath(Path.Combine(webRootPath, relative));

            return fullPath.StartsWith(uploadsRoot, StringComparison.OrdinalIgnoreCase) ? fullPath : null;
        }
    }
}
